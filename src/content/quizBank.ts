/** Evaluates mastery percentage and badge label */
export function calculateMastery(score: number, total: number) {
  const percentage = total > 0 ? Math.round((score / total) * 100) : 0;
  let label = 'Needs Review';
  let isMastered = false;

  if (percentage === 100) {
    label = 'Outstanding Mastery! 🏆';
    isMastered = true;
  } else if (percentage >= 66) {
    label = 'Mastery Achieved ⭐';
    isMastered = true;
  } else if (percentage > 0) {
    label = 'In Progress ✍️';
    isMastered = false;
  }

  return { percentage, label, isMastered };
}
